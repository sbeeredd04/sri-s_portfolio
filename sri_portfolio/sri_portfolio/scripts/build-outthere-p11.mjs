// Publish the supplied optimized delivery unchanged. --from-blend rebuilds the
// earlier fallback export when an intentional Blender source edit is required.
import { NodeIO } from "@gltf-transform/core";
import {
  ALL_EXTENSIONS,
  EXTMeshoptCompression,
} from "@gltf-transform/extensions";
import { dedup, prune, weld, meshopt } from "@gltf-transform/functions";
import { MeshoptDecoder, MeshoptEncoder } from "meshoptimizer";
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
await Promise.all([MeshoptDecoder.ready, MeshoptEncoder.ready]);
const io = new NodeIO()
  .registerExtensions(ALL_EXTENSIONS)
  .registerDependencies({
    "meshopt.decoder": MeshoptDecoder,
    "meshopt.encoder": MeshoptEncoder,
  });
const regenerated = process.argv.includes("--from-blend");
const source = regenerated
  ? "asset-src/authored/out-there/p11-raw.glb"
  : "asset-src/authored/out-there/p11-delivered-web.glb";
const target = "public/models/islands/out-there-p11.glb";
if (regenerated) {
  const doc = await io.read(source);
  await doc.transform(
    weld(),
    dedup(),
    prune(),
    meshopt({ encoder: MeshoptEncoder, level: "high" }),
  );
  doc.createExtension(EXTMeshoptCompression).setRequired(true);
  await io.write(target, doc);
} else await writeFile(target, await readFile(source));
const check = await io.read(target),
  root = check.getRoot();
for (const name of [
  "rock",
  "terrain",
  "pool",
  "lookout_vc",
  "bridges_paths_p8",
  "cable_station",
])
  if (!root.listNodes().some((n) => n.getName() === name))
    throw Error("Missing island node: " + name);
for (const mesh of root.listMeshes())
  for (const primitive of mesh.listPrimitives())
    if (
      primitive.getMaterial()?.getName() === "PT_Flat" &&
      !primitive.getAttribute("COLOR_0")
    )
      throw Error("Lost authored palette on " + mesh.getName());
const hooks = JSON.parse(
  await readFile("app/lib/out-there-p11-hooks.json", "utf8"),
);
const expected = [
  ...new Set(Object.values(hooks.animals).flatMap((a) => a.clips)),
].sort();
const actual = root
  .listAnimations()
  .map((a) => a.getName())
  .sort();
if (JSON.stringify(actual) !== JSON.stringify(expected))
  throw Error("Animal clip contract changed");
const reached = new Set(["ENTRY"]);
let changed = true;
while (changed) {
  changed = false;
  for (const [a, b] of hooks.path_edges) {
    if (!hooks.path_nodes[a] || !hooks.path_nodes[b])
      throw Error("Missing path endpoint");
    if (reached.has(a) !== reached.has(b)) {
      reached.add(a);
      reached.add(b);
      changed = true;
    }
  }
}
if (reached.size !== Object.keys(hooks.path_nodes).length)
  throw Error("Disconnected supplied hook graph");
const count = (m) =>
  m
    .listPrimitives()
    .reduce(
      (s, p) =>
        s +
        (p.getIndices()?.getCount() ?? p.getAttribute("POSITION").getCount()) /
          3,
      0,
    );
const bytes = await readFile(target),
  hash = createHash("sha256").update(bytes).digest("hex");
const stats = {
  source: {
    kind: regenerated
      ? "Blender fallback"
      : "Official supplied p11 web delivery",
    file: source,
    unchangedDelivery: !regenerated,
    blendSha256:
      "6cdc050a69edf314711dab05980bba81bb2dca26143d4ebe46e81c2e5ac2090c",
  },
  file: "models/islands/out-there-p11.glb",
  bytes: bytes.length,
  sha256: hash,
  uniqueMeshes: root.listMeshes().length,
  drawMeshes: root.listNodes().filter((n) => n.getMesh()).length,
  materials: root.listMaterials().length,
  animationClips: actual.length,
  uniqueTriangles: root.listMeshes().reduce((s, m) => s + count(m), 0),
  renderedTriangles: root
    .listNodes()
    .reduce((s, n) => s + (n.getMesh() ? count(n.getMesh()) : 0), 0),
  logicalNavigation: {
    nodes: reached.size,
    edges: hooks.path_edges.length,
    connected: true,
    physicalWalkingVerified: false,
  },
};
await writeFile(
  "asset-src/stats/out-there-p11.json",
  JSON.stringify(stats, null, 2) + "\n",
);
await writeFile(
  "app/lib/out-there-p11-build.mjs",
  `// Generated by scripts/build-outthere-p11.mjs.\nexport const outThereModelSource = "/models/islands/out-there-p11.glb?v=${hash.slice(0, 16)}";\n`,
);
console.log(JSON.stringify(stats, null, 2));
