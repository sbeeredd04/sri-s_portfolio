"""Asset export policy, importable without Blender for contract checks.

Semantic profiles must use a hierarchy-preserving exporter, never the static
optimizer. No runtime models are regenerated by defining these policies.
"""

PROFILES = ("static", "interactive", "vegetation", "rigged")


def export_options(profile):
    if profile not in PROFILES:
        raise ValueError(f"Unknown export profile: {profile!r}")
    semantic = profile != "static"
    rigged = profile == "rigged"
    return {
        "export_apply": not semantic,
        "export_extras": semantic,
        "export_attributes": semantic,
        "export_vertex_color": "ACTIVE" if semantic else "NONE",
        "export_animations": rigged or profile == "interactive",
        "export_skins": rigged,
        "export_morph": rigged,
    }


def require_static_profile(profile):
    export_options(profile)
    if profile != "static":
        raise ValueError(
            f"Profile {profile!r} cannot use optimize_model.py: it flattens "
            "hierarchy and discards semantic data. Use a preserving exporter."
        )
